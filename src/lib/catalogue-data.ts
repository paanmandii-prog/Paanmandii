/**
 * Converts a MasterProductRecord to the application's ProductWithDetails format
 */
export function toProductWithDetails(item: MasterProductRecord): ProductWithDetails {
  const isMukhya = item.category_slug === 'mukhya-saman'
  const category = MASTER_CATEGORIES.find((c) => c.slug === item.category_slug) || MASTER_CATEGORIES[0]

  // unit field on ProductWithDetails carries the full pack label e.g. "100 g / 100 ग्राम"
  const unitDisplay = item.unit_confirmed
    ? `${item.pack_size} / ${item.pack_size_hi}`
    : `${item.pack_size}`

  return {
    id: `prod-${item.source_id}`,
    sku: item.sku,
    name: item.name_en,
    slug: `item-${item.source_id}-${item.sku.toLowerCase()}`,
    description: item.description_en,
    category_id: category.id,
    unit: unitDisplay,
    base_price_paise: item.rate_inr * 100,
    mrp_paise: Math.round(item.rate_inr * 1.25) * 100,
    min_order_qty: item.min_order_qty,
    qty_increment: item.qty_increment,
    tax_rate_percent: 0,
    hsn_code: isMukhya ? '0802' : '2106',
    is_active: item.is_active,
    is_featured: item.is_featured,
    is_popular: item.is_popular,
    requires_legal_verification: item.compliance_status === 'review_required',
    weight_grams: null,
    dimensions_cm: null,
    tags: [item.category_slug, item.name_hi, item.sku],
    meta_title: `${item.name_en} (${item.name_hi}) — ₹${item.rate_inr} / पैक | PAAN MANDI`,
    meta_description: `Buy wholesale ${item.name_en} (${item.name_hi}) at mandi rate ₹${item.rate_inr} per pack (${item.pack_size}). Authentic Indian paan supplies.`,
    source_id: item.source_id,
    name_hi: item.name_hi,
    name_en: item.name_en,
    unit_confirmed: item.unit_confirmed,
    compliance_status: item.compliance_status,
    compliance_notes: item.compliance_notes,
    image_status: item.image_status,
    publication_status: item.publication_status,
    // Extra fields used in ProductCard
    pack_size: item.pack_size,
    pack_size_hi: item.pack_size_hi,
    created_at: new Date(2026, 0, parseInt(item.source_id, 10)).toISOString(),
    updated_at: new Date().toISOString(),
    images: [
      {
        id: `img-${item.source_id}-primary`,
        product_id: `prod-${item.source_id}`,
        url: `/images/products/${item.image_filename}`,
        alt_text: `${item.name_en} (${item.name_hi}) ${item.pack_size} — PAAN MANDI Wholesale`,
        sort_order: 1,
        is_primary: true,
        created_at: new Date().toISOString(),
      },
    ],
    price_tiers: [],
    inventory: {
      id: `inv-${item.source_id}`,
      product_id: `prod-${item.source_id}`,
      quantity_available: item.stock,
      quantity_reserved: 0,
      low_stock_threshold: 10,
      allow_backorder: false,
      updated_at: new Date().toISOString(),
    },
    category,
  }
}

export const ALL_39_PRODUCTS: ProductWithDetails[] = SOURCE_RATE_LIST.map(toProductWithDetails)

export function getProductBySlugOrId(identifier: string): ProductWithDetails | undefined {
  return ALL_39_PRODUCTS.find(
    (p) =>
      p.slug === identifier ||
      p.id === identifier ||
      p.sku.toLowerCase() === identifier.toLowerCase() ||
      p.source_id === identifier
  )
}
